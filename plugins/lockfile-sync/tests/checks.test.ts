import { describe, expect, test, tier } from 'claude-code/testing'

import { checkFor, gemCore, lockDir, type Ran } from '../hooks/checks.ts'
import { doneLines, doneLog, sidebarLines } from '../hooks/pairs.ts'

tier('user')

const ran = (exitCode: number, stdout: string, stderr = ''): Ran => ({ exitCode, stdout, stderr })

/** The verdict of a lockfile's check for one answer; the texts below are the tools' own, as measured. */
function judge(lock: string, answer: Ran, lockText = ''): string {
  const check = checkFor(lock, lockText)
  if (check === undefined) throw new Error(`no check for ${lock}`)
  return check.judge(answer, lockText)
}

const LOCK = `GEM
  remote: https://rubygems.org/
  specs:
    rake (13.4.2)

PLATFORMS
  arm64-darwin-25
  ruby

DEPENDENCIES
  rake (~> 13.0)

BUNDLED WITH
   4.0.11
`

describe('checks', () => {
  test('a pass is in step, the tool\'s own out-of-date text is behind, and any other failure proves nothing', () => {
    expect(judge('Cargo.lock', ran(0, '{}'))).toBe('in-sync')
    expect(judge('crates/a/Cargo.lock', ran(101, '', 'error: cannot update the lock file /x/Cargo.lock because --locked was passed to prevent this'))).toBe('behind')
    expect(judge('Cargo.lock', ran(101, '', 'error: failed to parse manifest'))).toBe('unknown')
    expect(judge('package-lock.json', ran(1, '', 'npm error `npm ci` can only install packages when your package.json and package-lock.json are in sync.'))).toBe('behind')
    expect(judge('pnpm-lock.yaml', ran(1, "  specifiers in the lockfile don't match specifiers in package.json:"))).toBe('behind')
    expect(judge('bun.lockb', ran(1, '', 'error: lockfile had changes, but lockfile is frozen'))).toBe('behind')
    expect(judge('composer.lock', ran(2, '- The lock file is not up to date with the latest changes in composer.json'))).toBe('behind')
    expect(judge('uv.lock', ran(1, '', 'The lockfile at `uv.lock` needs to be updated, but `--check` was provided.'))).toBe('behind')
    expect(judge('poetry.lock', ran(1, '', 'Error: pyproject.toml changed significantly since poetry.lock was last generated.'))).toBe('behind')
    expect(judge('pdm.lock', ran(1, '', "WARNING: Lockfile doesn't satisfy the project requirements, packages may be outdated"))).toBe('behind')
    expect(judge('Pipfile.lock', ran(1, 'Pipfile.lock is out-of-date. Run $ pipenv lock to update.'))).toBe('behind')
    expect(judge('pubspec.lock', ran(65, '', 'Unable to satisfy `pubspec.yaml` using `pubspec.lock`.'))).toBe('behind')
    expect(judge('mix.lock', ran(1, '', '** (Mix) Your mix.lock is out of date and must be updated without the --check-locked flag'))).toBe('behind')
  })

  test('go.sum is behind only when tidy would change it, not for an untidy go.mod alone', () => {
    expect(judge('go.sum', ran(0, ''))).toBe('in-sync')
    expect(judge('go.sum', ran(1, 'diff current/go.sum tidy/go.sum\n--- current/go.sum\n+++ tidy/go.sum\n'))).toBe('behind')
    expect(judge('go.sum', ran(1, '--- current/go.mod\n+++ tidy/go.mod\n'))).toBe('in-sync')
    expect(judge('go.sum', ran(1, '', 'go: updates to go.mod needed'))).toBe('unknown')
  })

  test('yarn check: a missing pattern is behind, errors about node_modules alone are in step', () => {
    const v1 = '# THIS IS AN AUTOGENERATED FILE.\n# yarn lockfile v1\n'
    expect(judge('yarn.lock', ran(1, '', 'error "is-number" not installed\nerror Found 1 errors.'), v1)).toBe('in-sync')
    expect(judge('yarn.lock', ran(1, '', 'error Lockfile does not contain pattern: "is-odd@^3.0.1"\nerror "is-odd" not installed\nerror Found 2 errors.'), v1)).toBe('behind')
    expect(judge('yarn.lock', ran(1, '', 'error An unexpected error occurred'), v1)).toBe('unknown')
    // Yarn 2 and later have no check that leaves the project alone.
    expect(checkFor('yarn.lock', '__metadata:\n  version: 8\n')).toBe(undefined)
  })

  test('Gemfile.lock compares what the Gemfile decides, not the platforms or the Bundler version', () => {
    const other = LOCK.replace('arm64-darwin-25', 'x86_64-linux').replace('4.0.11', '2.5.0')
    expect(gemCore(other)).toBe(gemCore(LOCK))
    expect(judge('Gemfile.lock', ran(0, other), LOCK)).toBe('in-sync')
    expect(judge('Gemfile.lock', ran(0, LOCK.replace('rake (~> 13.0)', 'rake (~> 13.0)\n  rack')), LOCK)).toBe('behind')
    // A print that was cut before DEPENDENCIES, or failed, proves nothing.
    expect(judge('Gemfile.lock', ran(0, 'GEM\n  specs:\n'), LOCK)).toBe('unknown')
    expect(judge('Gemfile.lock', ran(1, ''), LOCK)).toBe('unknown')
  })

  test('the argv, the environment and the directory of a check', () => {
    expect(checkFor('crates/Cargo.lock', '')?.argv('/r/crates/a/Cargo.toml')).toEqual(['cargo', 'metadata', '--locked', '--format-version', '1', '--manifest-path', '/r/crates/a/Cargo.toml'])
    expect(checkFor('mix.lock', '')?.env?.('/tmp/lockfile-sync')).toEqual({ MIX_DEPS_PATH: '/tmp/lockfile-sync/mix-deps' })
    expect(checkFor('mix.exs', '')).toBe(undefined)
    expect(lockDir('crates/Cargo.lock')).toBe('crates')
    expect(lockDir('Cargo.lock')).toBe('')
  })

  test('a closing names the package manager that read the lockfile as in step', () => {
    const settled = [{ manifest: 'Cargo.toml', lock: 'Cargo.lock', tool: 'cargo' }, { manifest: 'package.json', lock: 'package-lock.json' }]
    expect(doneLog([], settled)).toBe('the dependencies match the lockfile again: package.json · cargo reads Cargo.lock as in step with Cargo.toml')
    expect(doneLines([], settled).map(l => l.text)).toEqual(['cargo reads Cargo.lock as in step with Cargo.toml', 'package.json asks for no lockfile change any more'])
  })

  test('the sidebar colours the lockfile: red while it is behind, green once it closes, the rest faint', () => {
    const pair = { manifest: 'package.json', lock: 'package-lock.json' }
    expect(sidebarLines([pair])).toEqual([
      { text: 'package.json but not package-lock.json', parts: [{ text: 'package.json' }, { text: ' but not ', kind: 'dim' }, { text: 'package-lock.json', kind: 'error' }] },
    ])
    expect(doneLines([pair], [{ ...pair, tool: 'npm' }, pair])).toEqual([
      { text: 'package-lock.json now matches package.json', parts: [{ text: 'package-lock.json', kind: 'ok' }, { text: ' now matches package.json', kind: 'dim' }] },
      {
        text: 'npm reads package-lock.json as in step with package.json',
        parts: [{ text: 'npm reads ', kind: 'dim' }, { text: 'package-lock.json', kind: 'ok' }, { text: ' as in step with package.json', kind: 'dim' }],
      },
      { text: 'package.json asks for no lockfile change any more', parts: [{ text: 'package.json', kind: 'ok' }, { text: ' asks for no lockfile change any more', kind: 'dim' }] },
    ])
  })
})
